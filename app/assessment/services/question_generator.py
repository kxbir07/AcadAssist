class DeterministicQuestionGenerator(BaseQuestionGenerator):
    """Deterministic question generator supplying standard academic questions with template fallback."""

    def __init__(self, bank: Optional[List[Dict[str, Any]]] = None):
        self.bank = bank or list(QUESTION_BANK)

    def generate_candidate_questions(
        self,
        subject_id: str,
        topic_ids: Optional[List[str]] = None,
        difficulty: str = "medium",
        count: int = 10,
    ) -> List[Dict[str, Any]]:
        """Retrieve matching candidate questions from bank, dynamically generating rich variants if needed."""
        target_subject = subject_id.strip().lower()
        target_diff = difficulty.strip().lower()

        # Normalize topic_ids
        target_topics = (
            [t.strip().lower() for t in topic_ids] if topic_ids else None
        )

        matches: List[Dict[str, Any]] = []

        # 1. First pass: exact subject, topic, and difficulty match
        for q in self.bank:
            q_subj = q.get("subject_id", "").strip().lower()
            q_top = q.get("topic_id", "").strip().lower()
            q_diff = q.get("difficulty", "").strip().lower()

            if q_subj == target_subject or target_subject in q_subj:
                if target_topics is None or q_top in target_topics:
                    if q_diff == target_diff:
                        matches.append(dict(q))

        # 2. Second pass: match subject & topic regardless of difficulty if candidates < count * 3
        if len(matches) < count * 3:
            for q in self.bank:
                q_subj = q.get("subject_id", "").strip().lower()
                q_top = q.get("topic_id", "").strip().lower()
                if q_subj == target_subject or target_subject in q_subj:
                    if target_topics is None or q_top in target_topics:
                        if dict(q) not in matches:
                            matches.append(dict(q))

        # 3. Third pass: if question bank needs more candidate pool for heavy no-repeat testing,
        # generate deterministic template-based questions so that we can support large question pools.
        base_topic = (
            topic_ids[0] if topic_ids else "Operating Systems Concepts"
        )
        extra_index = 1
        while len(matches) < count + 50:
            synthetic_q = {
                "subject_id": subject_id,
                "topic_id": base_topic,
                "difficulty": target_diff,
                "question_text": f"Evaluate academic concept {base_topic} variant #{extra_index}: What is the primary characteristic of {base_topic} configuration #{extra_index}?",
                "question_type": "multiple_choice",
                "options": [
                    f"Option A for {base_topic} variant {extra_index}",
                    f"Option B (Correct) for {base_topic} variant {extra_index}",
                    f"Option C for {base_topic} variant {extra_index}",
                    f"Option D for {base_topic} variant {extra_index}",
                ],
                "correct_answer": f"Option B (Correct) for {base_topic} variant {extra_index}",
                "explanation": f"Detailed academic explanation for {base_topic} concept variant #{extra_index}.",
                "source_chunk_id": f"chunk_synthetic_{extra_index:03d}",
            }
            matches.append(synthetic_q)
            extra_index += 1

        return matches


class AIQuestionGeneratorAdapter(BaseQuestionGenerator):
    """Adapter interface for future AI/RAG question generation.

    Integrates with Person 1's Foundry models or Person 2's RAG pipeline when available,
    while falling back safely to deterministic generation.
    """

    def __init__(self, fallback_generator: Optional[BaseQuestionGenerator] = None):
        self.fallback = fallback_generator or DeterministicQuestionGenerator()

    def generate_candidate_questions(
        self,
        subject_id: str,
        topic_ids: Optional[List[str]] = None,
        difficulty: str = "medium",
        count: int = 10,
    ) -> List[Dict[str, Any]]:
        # In V1, cleanly delegating to deterministic generation
        # Future AI implementations can hook into this adapter
        return self.fallback.generate_candidate_questions(
            subject_id=subject_id,
            topic_ids=topic_ids,
            difficulty=difficulty,
            count=count,
        )

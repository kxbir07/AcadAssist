"""Question generation boundary and deterministic question bank for Person 3 Assessment Subsystem.

Provides an extensible question generation abstraction supporting deterministic question
pools, template expansion for testing/simulation, and integration hooks for future AI/RAG generators.
"""

from abc import ABC, abstractmethod
from typing import List, Dict, Any, Optional
import uuid


class BaseQuestionGenerator(ABC):
    """Abstract interface for assessment question generators."""

    @abstractmethod
    def generate_candidate_questions(
        self,
        subject_id: str,
        topic_ids: Optional[List[str]] = None,
        difficulty: str = "medium",
        count: int = 10,
    ) -> List[Dict[str, Any]]:
        """Generate a list of candidate questions.

        Returns:
            List of dicts with keys: question_text, question_type, difficulty,
            options, correct_answer, explanation, subject_id, topic_id, source_chunk_id
        """
        pass


